"""Merge a recording-chain preset (experiments/chain/<preset>.toml) over every scenario in a sim dir and
write experiments/sim_chain_<preset>/*.toml. Preset tables override the scenario's key by key.
Deterministic; rerun to regenerate.
Usage: python3 -I tools/gen_sim_chain.py <preset name | preset.toml path> [--src experiments/sim_atm] [--out DIR]"""

import argparse
import pathlib
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent


def merge(base: dict, over: dict) -> dict:
    out = dict(base)
    for k, v in over.items():
        out[k] = merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def scalar(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "[" + ", ".join(scalar(x) for x in v) + "]"
    return repr(v)


def emit(d: dict, prefix: str = "") -> list[str]:
    """Minimal TOML writer for the scenario schema: scalars, arrays, tables, arrays of tables."""
    lines = [f"{k} = {scalar(v)}" for k, v in d.items() if not isinstance(v, dict) and not is_table_array(v)]
    for k, v in d.items():
        name = f"{prefix}{k}"
        if isinstance(v, dict):
            lines += ["", f"[{name}]", *emit(v, name + ".")]
        elif is_table_array(v):
            for item in v:
                lines += ["", f"[[{name}]]", *emit(item, name + ".")]
    return lines


def is_table_array(v) -> bool:
    return isinstance(v, list) and bool(v) and all(isinstance(x, dict) for x in v)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("preset")
    ap.add_argument("--src", default="experiments/sim_atm")
    ap.add_argument("--out")
    a = ap.parse_args()
    given = pathlib.Path(a.preset)
    preset_path = given if given.suffix == ".toml" else ROOT / "experiments" / "chain" / f"{a.preset}.toml"
    preset = tomllib.loads(preset_path.read_text())
    src = ROOT / a.src
    out = pathlib.Path(a.out) if a.out else ROOT / "experiments" / f"sim_chain_{preset_path.stem}"
    out.mkdir(parents=True, exist_ok=True)
    n = 0
    for f in sorted(src.glob("*.toml")):
        sc = merge(tomllib.loads(f.read_text()), preset)
        aircraft = sc.pop("aircraft")
        head = f"# Generated by tools/gen_sim_chain.py: {a.src}/{f.name} + {preset_path.name}\n"
        body = emit(sc) + emit({"aircraft": aircraft})
        (out / f.name).write_text(head + "\n".join(body).lstrip("\n") + "\n")
        n += 1
    print(f"wrote {n} scenarios to {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}")


if __name__ == "__main__":
    main()
