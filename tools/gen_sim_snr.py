"""Write experiments/sim_snr/*.toml: an SNR ladder for scoring comparisons. Ten single-aircraft geometries,
each with two silent ADS-B-only distractor flights (harmonics all zero: tracks, no sound, no event) of
similar speed and height passing 1.5-4 km from the observer with CPA within +-1.5 s of the truth's, rendered at
source levels 0 to -22 dB in 2 dB steps below a common reference (fundamental +16 dB in 1 Hz at CPA). The
level is in the file name (snr_mXX = -XX dB). Run with a +-2 s clock prior (experiments/snr_*.toml):
under a wide prior a single event is degenerate along track and rank 1 is trivially reached.
Deterministic; rerun to regenerate. Usage: python3 -I tools/gen_sim_snr.py"""

import math
import pathlib
import random

OUT = pathlib.Path(__file__).resolve().parent.parent / "experiments" / "sim_snr"
LEVELS_DB = list(range(0, -24, -2))

HEADER = """# Generated by tools/gen_sim_snr.py; geometry {g}, source level {lvl:+d} dB.
seed = {seed}
sample_rate = 4000
duration_s = 120.0
start_unix = 1725827400.0
adsb_dt_s = 1.0

[observer]
lat_deg = 38.912
lon_deg = -97.214
h_ell_m = 360.0
mic_height_m = 1.5

[ground]
reflection = 0.6

[noise]
snr_db = 0.0
red_db = 12.0
red_corner_hz = 60.0

[device]
highpass_hz = 40.0
"""

AIRCRAFT = """
[[aircraft]]
id = "{icao:06x}-0"
icao24 = 0x{icao:06X}
type_code = "C172"
engine = "Piston"
amplitude = {amp:.5f}
[aircraft.source]
f0 = {f0:.1f}
harmonics = {harm}
jitter_frac = 0.001
[aircraft.straight]
heading_deg = {hdg:.0f}
speed_mps = {v:.0f}
alt_agl_m = {alt:.0f}
cpa_offset_m = {off:.0f}
cpa_time_s = {tc:.1f}
half_span_s = 200.0
"""


def geometry(rng):
    alt = rng.choice([300, 500, 800, 1200])
    off = rng.uniform(-1.5, 1.5) * alt
    return dict(alt=alt, off=off, f0=rng.uniform(80, 140), hdg=rng.uniform(0, 360), v=rng.uniform(50, 90))


def distractor(rng, g):
    # Same speed band and similar slant, so it passes association for cells 1-4 km from the truth.
    alt = g["alt"] * rng.uniform(0.8, 1.25)
    off = math.copysign(rng.uniform(1500, 4000), rng.choice([-1, 1]))
    v = g["v"] * rng.uniform(0.9, 1.1)
    return dict(alt=alt, off=off, f0=rng.uniform(80, 140), hdg=rng.uniform(0, 360), v=v)


def block(icao, g, amp, harm, tc):
    return AIRCRAFT.format(icao=icao, amp=amp, harm=harm, tc=tc, **g)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rng = random.Random(20261104)
    for gi in range(10):
        g = geometry(rng)
        slant = math.hypot(g["alt"], g["off"])
        # Reference: per-1 Hz-band SNR of the fundamental at CPA = +16 dB (amplitude ∝ slant cancels spreading).
        ref = 10 ** (16 / 20) * slant / 1000.0
        # Distractor CPA emission times within ±1.5 s of the truth's: clock-compatible under a ±2 s prior
        # for cells near their own paths.
        ds = [(distractor(rng, g), 60.0 + rng.uniform(-1.5, 1.5)) for _ in range(2)]
        for lvl in LEVELS_DB:
            body = HEADER.format(g=gi, lvl=lvl, seed=300 + gi)
            body += block(0xA80000 + 16 * gi, g, ref * 10 ** (lvl / 20), "[1.0, 0.6, 0.4]", 60.0)
            for k, (d, tc) in enumerate(ds):
                body += block(0xA80001 + 16 * gi + k, d, 0.0, "[0.0]", tc)
            (OUT / f"snr_g{gi:02d}_m{-lvl:02d}.toml").write_text(body)


if __name__ == "__main__":
    main()
