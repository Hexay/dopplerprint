"""Regenerate the case table inside data/MANIFEST.md (between the TABLE markers) from each case's truth.json."""
import json
import re

from .common import CASES, DATA, log

BEGIN, END = "<!-- TABLE:BEGIN (generated by fetch_corpus.py manifest) -->", "<!-- TABLE:END -->"


def _size(path):
    n = sum(p.stat().st_size for p in path.rglob("*") if p.is_file())
    return f"{n / 1e6:,.0f} MB" if n >= 1e6 else f"{n / 1e3:,.0f} kB"


def _has(case, sub):
    d = case / sub
    return d.is_dir() and any(p.is_file() for p in d.rglob("*"))


def row(case):
    t = json.loads((case / "truth.json").read_text())
    loc = "lat" in t or "reference_origin" in t
    time = any(k in t for k in ("recording_start_utc", "recording_start_window_utc", "recording_clock"))
    adsb = _has(case, "adsb") or bool(t.get("background_adsb"))
    dem = _has(case, "dem") or "constant" in str(t.get("terrain", ""))
    full = all([_has(case, "audio"), loc, time, adsb, dem])
    missing = [m for m, ok in [("audio", _has(case, "audio")), ("location", loc), ("time", time),
                               ("adsb", adsb), ("dem", dem)] if not ok]
    if t.get("kind") == "real" and t["case_id"].startswith("livermore") and not t.get("background_adsb"):
        missing.append("background ADS-B day")
    missing += t.get("missing", [])[:1]
    lic = t.get("license", "").split(";")[0].split("(")[0].strip()
    return (f"| {t['case_id']} | {t.get('kind')} | {t.get('source_url', '')} | {lic} | "
            f"{'yes' if full else 'partial'} | {t.get('location_confidence', '').split(':')[0]} | "
            f"{'yes' if _has(case, 'baseline') else 'no'} | {_size(case)} | {', '.join(missing) or '-'} |")


def write():
    head = ("| case | kind | source | license | full truth | loc. confidence | baseline | size | missing |\n"
            "|---|---|---|---|---|---|---|---|---|")
    rows = [row(c) for c in sorted(CASES.iterdir()) if (c / "truth.json").exists()]
    table = f"{BEGIN}\n{head}\n" + "\n".join(rows) + f"\n{END}"
    path = DATA / "MANIFEST.md"
    text = path.read_text() if path.exists() else f"# Corpus manifest\n\n{BEGIN}\n{END}\n"
    path.write_text(re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda _: table, text, flags=re.S))
    log(f"MANIFEST table: {len(rows)} cases")
