"""Write experiments/sim_atm/*.toml: GA/turboprop flyovers rendered in a known non-default atmosphere
(c = 337 m/s, ~10 °C; 6 m/s wind toward the east) so model-atmosphere mismatch can be measured with exact
truth. Deterministic; rerun to regenerate. Usage: python3 -I tools/gen_sim_atm.py"""

import math
import pathlib
import random

OUT = pathlib.Path(__file__).resolve().parent.parent / "experiments" / "sim_atm"
C_TRUE, WIND = 337.0, [6.0, 0.0, 0.0]

HEADER = """# Generated by tools/gen_sim_atm.py; true atmosphere c = {c}, wind_enu = {w}.
seed = {seed}
sample_rate = 4000
duration_s = {dur}
start_unix = 1725827400.0
adsb_dt_s = 1.0

[observer]
lat_deg = 38.912
lon_deg = -97.214
h_ell_m = 360.0
mic_height_m = 1.5

[atmosphere]
c = {c}
wind_enu = {w}

[ground]
reflection = 0.6

[noise]
snr_db = 18.0
red_db = 12.0
red_corner_hz = 60.0

[device]
highpass_hz = 40.0
"""

AIRCRAFT = """
[[aircraft]]
id = "{icao:06x}-0"
icao24 = 0x{icao:06X}
type_code = "C172"
engine = "Piston"
amplitude = {amp:.2f}
[aircraft.source]
f0 = {f0:.1f}
harmonics = [1.0, 0.6, 0.4]
jitter_frac = 0.001
[aircraft.straight]
heading_deg = {hdg:.0f}
speed_mps = {v:.0f}
alt_agl_m = {alt:.0f}
cpa_offset_m = {off:.0f}
cpa_time_s = {tc:.1f}
half_span_s = 200.0
"""


def aircraft(rng, icao, tc, hdg):
    alt = rng.choice([300, 500, 800, 1200, 1800])
    off = rng.uniform(-1.5, 1.5) * alt
    slant = math.hypot(alt, off)
    return AIRCRAFT.format(
        icao=icao, amp=0.4 * max(1.0, slant / 1000.0), f0=rng.uniform(80, 140), hdg=hdg,
        v=rng.uniform(45, 95), alt=alt, off=off, tc=tc,
    )


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rng = random.Random(20261103)
    for i in range(12):
        body = HEADER.format(c=C_TRUE, w=WIND, seed=100 + i, dur=120.0)
        body += aircraft(rng, 0xA70000 + i, 60.0, rng.uniform(0, 360))
        (OUT / f"atm_single_{i:02d}.toml").write_text(body)
    for i in range(6):
        h1 = rng.uniform(0, 360)
        body = HEADER.format(c=C_TRUE, w=WIND, seed=200 + i, dur=260.0)
        body += aircraft(rng, 0xA71000 + 2 * i, 60.0, h1)
        body += aircraft(rng, 0xA71001 + 2 * i, 200.0, (h1 + rng.uniform(90, 180)) % 360)
        (OUT / f"atm_pair_{i:02d}.toml").write_text(body)


if __name__ == "__main__":
    main()
