"""Write experiments/sim_calib/*.toml: the calibration sim bank. 1, 2 and 3 straight GA flyovers per
recording, each recording in its own mildly wrong atmosphere (c 337-349 m/s, wind 0-6 m/s, random
direction) so the model's fixed c = 343 / no wind carries realistic error. `cal_*` cases fit T and q̂;
`test_*` cases are held out. Deterministic; rerun to regenerate. Usage: python3 -I tools/gen_sim_calib.py"""

import math
import pathlib
import random

OUT = pathlib.Path(__file__).resolve().parent.parent / "experiments" / "sim_calib"
SPLITS = {"cal": 20, "test": 12}
GAP_S = 140.0

HEADER = """# Generated by tools/gen_sim_calib.py; true atmosphere c = {c:.1f}, wind_enu = {w}.
seed = {seed}
sample_rate = 4000
duration_s = {dur}
start_unix = 1725827400.0
adsb_dt_s = 1.0

[observer]
lat_deg = {lat:.4f}
lon_deg = {lon:.4f}
h_ell_m = 360.0
mic_height_m = 1.5

[atmosphere]
c = {c:.1f}
wind_enu = {w}

[ground]
reflection = 0.6

[noise]
snr_db = {snr:.0f}
red_db = 12.0
red_corner_hz = 60.0

[device]
highpass_hz = 40.0
"""

AIRCRAFT = """
[[aircraft]]
id = "{icao:06x}-0"
icao24 = 0x{icao:06X}
type_code = "C172"
engine = "Piston"
amplitude = {amp:.2f}
[aircraft.source]
f0 = {f0:.1f}
harmonics = [1.0, 0.6, 0.4]
jitter_frac = 0.001
[aircraft.straight]
heading_deg = {hdg:.0f}
speed_mps = {v:.0f}
alt_agl_m = {alt:.0f}
cpa_offset_m = {off:.0f}
cpa_time_s = {tc:.1f}
half_span_s = 200.0
"""


def aircraft(rng, icao, tc, hdg):
    alt = rng.choice([300, 500, 800, 1200, 1800])
    off = rng.uniform(-1.5, 1.5) * alt
    slant = math.hypot(alt, off)
    return AIRCRAFT.format(
        icao=icao, amp=0.4 * max(1.0, slant / 1000.0), f0=rng.uniform(80, 140), hdg=hdg,
        v=rng.uniform(45, 95), alt=alt, off=off, tc=tc,
    )


def recording(rng, seed, n_pass, icao0):
    wind, wdir = rng.uniform(0, 6), rng.uniform(0, 2 * math.pi)
    w = [round(wind * math.sin(wdir), 2), round(wind * math.cos(wdir), 2), 0.0]
    body = HEADER.format(
        c=rng.uniform(337, 349), w=w, seed=seed, dur=60.0 + GAP_S * (n_pass - 1) + 60.0,
        lat=38.912 + rng.uniform(-0.2, 0.2), lon=-97.214 + rng.uniform(-0.2, 0.2), snr=rng.uniform(14, 22),
    )
    h = rng.uniform(0, 360)
    for k in range(n_pass):
        body += aircraft(rng, icao0 + k, 60.0 + GAP_S * k, h)
        h = (h + rng.uniform(60, 150)) % 360
    return body


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rng = random.Random(20261104)
    seed = 1000
    for split, n in SPLITS.items():
        for n_pass in (1, 2, 3):
            for i in range(n):
                seed += 1
                icao0 = 0xB00000 + seed * 4
                (OUT / f"{split}_{n_pass}p_{i:02d}.toml").write_text(recording(rng, seed, n_pass, icao0))


if __name__ == "__main__":
    main()
